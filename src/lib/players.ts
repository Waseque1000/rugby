const MINIMUM_PLAYER_PROFILE_SCORE = 4;
const BAD_CLUB_VALUE = /^(?:\d{4}|.*\bseries\b|.*\bselection\b)/i;

function getAge(dob: string | null): number | null {
  if (!dob) return null;
  const birthDate = new Date(`${dob}T00:00:00Z`);
  if (Number.isNaN(birthDate.getTime())) return null;

  const now = new Date();
  let age = now.getUTCFullYear() - birthDate.getUTCFullYear();
  const birthdayHasPassed =
    now.getUTCMonth() > birthDate.getUTCMonth() ||
    (now.getUTCMonth() === birthDate.getUTCMonth() &&
      now.getUTCDate() >= birthDate.getUTCDate());
  if (!birthdayHasPassed) age -= 1;
  return age >= 0 ? age : null;
}

function getCompletenessScore(player: Player): number {
  return [
    player.position,
    player.hometown,
    player.college,
    player.club && !BAD_CLUB_VALUE.test(player.club) ? player.club : null,
    player.dob,
    player.olympicEditions.length > 0 ? "Olympic record" : null,
  ].filter(Boolean).length;
}

export function getPlayerIntro(player: Player): string {
  const team = player.team?.toLowerCase().includes("women")
    ? "USA women's"
    : player.team?.toLowerCase().includes("men")
      ? "USA men's"
      : "USA";
  const parts = [`${player.name} is listed in the ${team} rugby sevens records.`];
  if (player.position) parts.push(`Position: ${player.position}.`);
  if (player.hometown) parts.push(`Hometown: ${player.hometown}.`);
  if (player.college) parts.push(`College: ${player.college}.`);
  if (player.club) parts.push(`Club: ${player.club}.`);
  if (player.olympicEditions.length) {
    parts.push(`Olympic appearances: ${player.olympicEditions.join(", ")}.`);
  }
  return parts.join(" ");
}

function normalizePlayer(player: Player): Player {
  const club = player.club && !BAD_CLUB_VALUE.test(player.club) ? player.club : null;
  const normalized = {
    ...player,
    age: getAge(player.dob),
    club,
    completenessScore: 0,
    indexable: false,
  };
  const completenessScore = getCompletenessScore(normalized);
  return {
    ...normalized,
    completenessScore,
    indexable: completenessScore >= MINIMUM_PLAYER_PROFILE_SCORE,
  };
}

export function getAllPlayers(): Player[] {
  return (playersData as Player[]).map(normalizePlayer);
}

export function getPlayerBySlug(slug: string): Player | undefined {
  const all = getAllPlayers();
  return all.find((p) => p.slug === slug || p.id === slug);
}

export function getFeaturedPlayers(limit = 6): Player[] {
  const all = getAllPlayers();
  // Highlight marquee names and multi-Olympic stars first
  const marqueeSlugs = [
    "usa-perry-baker",
    "usa-alev-kelter",
    "usa-carlin-isles",
    "usa-madison-hughes",
    "usa-sammy-sullivan",
    "usa-stephen-tomasin",
    "usa-kristi-kirshe",
    "usa-nate-ebner",
  ];

  const marquee = all.filter((p) => p.indexable && marqueeSlugs.includes(p.slug));
  const others = all.filter((p) => p.indexable && !marqueeSlugs.includes(p.slug) && p.isOlympian);
  
  return [...marquee, ...others].slice(0, limit);
}

export function getRelatedPlayers(current: Player, limit = 4): Player[] {
  const all = getAllPlayers();
  return all
    .filter((p) => p.slug !== current.slug && p.indexable)
    .sort((a, b) => {
      let scoreA = 0;
      let scoreB = 0;

      // Same college
      if (current.college && a.college && a.college.toLowerCase() === current.college.toLowerCase()) scoreA += 3;
      if (current.college && b.college && b.college.toLowerCase() === current.college.toLowerCase()) scoreB += 3;

      // Same team
      if (a.team && current.team && a.team.toLowerCase() === current.team.toLowerCase()) scoreA += 2;
      if (b.team && current.team && b.team.toLowerCase() === current.team.toLowerCase()) scoreB += 2;

      // Both Olympians
      if (a.isOlympian && current.isOlympian) scoreA += 1;
      if (b.isOlympian && current.isOlympian) scoreB += 1;

      return scoreB - scoreA;
    })
    .slice(0, limit);
}

export function getPlayerStatsSummary() {
  const all = getAllPlayers();
  const totalPlayers = all.length;
  const olympians = all.filter((p) => p.isOlympian).length;
  const mensCount = all.filter((p) => {
    const team = p.team?.toLowerCase() || "";
    return team.includes("men") && !team.includes("women");
  }).length;
  const womensCount = all.filter((p) => p.team?.toLowerCase().includes("women")).length;
  
  const colleges = new Set(
    all.map((p) => p.college).filter((c): c is string => Boolean(c && c.trim()))
  );

  return {
    totalPlayers,
    olympians,
    mensCount,
    womensCount,
    collegesCount: colleges.size,
  };
}

