const HUB_DIMENSIONS: Array<{
  key: PlayerHubDimension;
  label: string;
  values: (player: Player) => string[];
}> = [
  { key: "olympics", label: "Olympic editions", values: (player) => player.olympicEditions },
  { key: "colleges", label: "Colleges", values: (player) => (player.college ? [player.college] : []) },
  { key: "states", label: "Hometown states", values: (player) => (player.hometownState ? [player.hometownState] : []) },
  { key: "positions", label: "Positions", values: (player) => (player.position ? [player.position] : []) },
];

export function toHubSlug(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

export function getAllPlayerHubs(): PlayerHub[] {
  const players = getAllPlayers();
  return HUB_DIMENSIONS.flatMap(({ key, label, values }) => {
    const grouped = new Map<string, Player[]>();
    for (const player of players) {
      for (const value of values(player)) {
        grouped.set(value, [...(grouped.get(value) || []), player]);
      }
    }

    return [...grouped.entries()]
      .filter(([, group]) => group.length >= 2)
      .map(([value, group]) => ({
        dimension: key,
        dimensionLabel: label,
        slug: toHubSlug(value),
        value,
        players: group,
      }));
  }).sort((a, b) => a.dimensionLabel.localeCompare(b.dimensionLabel) || a.value.localeCompare(b.value));
}

export function getPlayerHub(dimension: string, slug: string): PlayerHub | undefined {
  return getAllPlayerHubs().find((hub) => hub.dimension === dimension && hub.slug === slug);
}

export function getListBySlug(slug: string): AutoGeneratedList | undefined {
  return getAllLists().find((l) => l.slug === slug);
}
